#!/usr/bin/env python3
"""Writes the package graphs the compiler reads, from Nahr's Supax.toml files.

SultanC does not read Supax.toml: the package manager (Supax) turns the
manifests into one package graph per build and passes it to the compiler with
--package-graph. This script does the same for Nahr's own consumers, so they
build with sultanc alone:

    examples/package-graph.toml   the examples, which depend on nahr
    tests/package-graph.toml      the tests
    bench/package-graph.toml      the benchmark servers

Each graph has the consumer package (its own directory), the nahr package
(src/, with its Arabic name) and the edge between them. The Arabic names of
Nahr's directories are not in the graph: src/nahr.sn, the package's root
file, declares them (`module routing { ar: توجيه };`).
Paths are relative to the graph file, so the files work from any checkout.
Run it after changing a Supax.toml:

    python3 tools/package_graphs.py
"""
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONSUMERS = ["examples", "tests", "bench"]


def quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def spellings(table: dict) -> str:
    return "{ " + ", ".join(f"{lang} = {quote(name)}" for lang, name in table.items()) + " }"


def graph(consumer: str, nahr: dict, own: dict) -> str:
    names = dict(nahr["package"].get("names", {}))
    canonical = nahr["package"]["name"]
    extra = {lang: name for lang, name in names.items() if name != canonical}
    lib = nahr.get("lib", {}).get("path", ".")
    lines = [
        f"# Generated by tools/package_graphs.py from Supax.toml and {consumer}/Supax.toml.",
        "# The compiler reads it with --package-graph; Supax writes its own in build/supax/.",
        "version = 1",
        f"root = {quote(own['package']['name'])}",
        "",
        "[[package]]",
        f"id = {quote(own['package']['name'])}",
        'source_root = "."',
        f"name = {quote(own['package']['name'])}",
        "",
        "[[package]]",
        f"id = {quote(canonical)}",
        f"source_root = {quote('../' + lib)}",
        f"name = {quote(canonical)}",
    ]
    if extra:
        lines.append(f"spellings = {spellings(extra)}")
    for dep in own.get("dependencies", {}):
        lines += ["", "[[edge]]", f"from = {quote(own['package']['name'])}", f"to = {quote(canonical)}", f"name = {quote(dep)}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    nahr = tomllib.loads((ROOT / "Supax.toml").read_text(encoding="utf-8"))
    for consumer in CONSUMERS:
        own = tomllib.loads((ROOT / consumer / "Supax.toml").read_text(encoding="utf-8"))
        target = ROOT / consumer / "package-graph.toml"
        target.write_text(graph(consumer, nahr, own), encoding="utf-8")
        print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
